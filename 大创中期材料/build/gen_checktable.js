// ---------- helpers ----------
function run(text, { bold = false, size = 21, font = "SimSun", color = BLACK } = {}) {
  return new TextRun({ text, bold, size, color, font: { ascii: "Times New Roman", eastAsia: font } });
}
function bodyP(text, { indent = true, align = AlignmentType.JUSTIFIED, bold = false, size = 21, before = 60, after = 60 } = {}) {
  return new Paragraph({
    alignment: align,
    spacing: { line: 312, before, after },
    indent: indent ? { firstLine: 420 } : undefined,
    children: [run(text, { bold, size })],
  });
}
function leadP(lead, rest, { size = 21 } = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 312, before: 60, after: 60 },
    indent: { firstLine: 420 },
    children: [run(lead, { bold: true, size, font: "SimHei" }), run(rest, { size })],
  });
}
function cell(children, { span, pct, fill, vAlign } = {}) {
  return new TableCell({
    columnSpan: span,
    width: { size: pct, type: WidthType.PERCENTAGE },
    shading: fill ? { type: ShadingType.CLEAR, fill } : undefined,
    verticalAlign: vAlign,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children,
  });
}
function labelCell(text, pct = 16) {
  return cell([new Paragraph({
    alignment: AlignmentType.CENTER, spacing: { line: 312 },
    children: [run(text, { font: "SimHei" })],
  })], { pct, vAlign: VerticalAlign.CENTER });
}
function valueCell(text, { span, pct = 34, align = AlignmentType.LEFT } = {}) {
  return cell([new Paragraph({
    alignment: align, spacing: { line: 312 },
    children: [run(text)],
  })], { span, pct, vAlign: VerticalAlign.CENTER });
}
// 章节标题行 / 章节内容行（同属外层大表）
function rowTitle(text) {
  return new TableRow({
    cantSplit: true,
    children: [cell([new Paragraph({
      spacing: { line: 312 },
      children: [run(text, { bold: true, size: 22, font: "SimHei" })],
    })], { span: 4, pct: 100, fill: SECTION_FILL })],
  });
}
function rowContent(children) {
  return new TableRow({
    children: [cell(children, { span: 4, pct: 100 })],
  });
}
// 嵌套表所在行：表后必须跟一个段落（OOXML 要求单元格以段落结尾）
function rowNested(nested) {
  return new TableRow({
    children: [cell([
      nested,
      new Paragraph({ spacing: { line: 100 }, children: [] }),
    ], { span: 4, pct: 100 })],
  });
}
function headRow(cols, pcts) {
  return new TableRow({
    tableHeader: true, cantSplit: true,
    children: cols.map((t, i) => cell([new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { line: 312 },
      children: [run(t, { bold: true })],
    })], { pct: pcts[i], fill: HEADER_FILL, vAlign: VerticalAlign.CENTER })),
  });
}

